fun kotlinConfiguration(config: GlassConfig): String =
    "GlassConfig(values = mapOf(\n" +
        Param.entries
            .filter { it.category != Category.TRANSITION }
            .joinToString(",\n") { "    Param.${it.name} to ${config[it]}f" } +
        "\n))"

private val COMPONENT_SOURCE =
    """
    @Composable
    fun ExportedGlassComponent(config: GlassConfig, modifier: Modifier = Modifier, target: Target = Target.MINI,
        backdropContent: @Composable BoxScope.() -> Unit,
        glassContent: @Composable BoxScope.() -> Unit) {
        val backdrop = rememberGlassBackdrop()
        val density = LocalDensity.current.density
        BoxWithConstraints(modifier) {
            val width = constraints.maxWidth.toFloat()
            val height = constraints.maxHeight.toFloat()
            val baseWidth = when(target) {
                Target.PLUS, Target.HOME -> 60f * density
                Target.CAPSULE -> ((width - 108f * density) / 3f - 8f * density).coerceIn(38f*density,96f*density)
                Target.NAVBAR -> width - 96f * density
                Target.MINI_COMPACT -> width - 164f * density
                else -> width - 22f * density
            }
            val baseHeight = when(target) { Target.CAPSULE -> 50f; Target.MINI -> 67f; else -> 60f }
            val deformation = config[Param.DEFORMATION]
            val w = (baseWidth * config[Param.WIDTH] * (1f+deformation)).coerceIn(38f*density,width)
            val h = baseHeight * density * config[Param.HEIGHT] * (1f-deformation)
            val center = Offset(width / 2 + config[Param.X] * density, height / 2 + config[Param.Y] * density)
            val rect = Rect(center - Offset(w / 2, h / 2), Size(w, h))
            Box(Modifier.fillMaxSize().recordBackdrop(backdrop), content = backdropContent)
            GlassField(backdrop, { listOf(GlassSurface(rect,
                (config[Param.RADIUS] * density * config[Param.CURVATURE]).coerceAtMost(h / 2), config)) }, Modifier.fillMaxSize())
            Box(Modifier.offset { IntOffset(rect.left.toInt(), rect.top.toInt()) }
                .size((w / density).dp, (h / density).dp), content = glassContent)
        }
    }
    """
        .trimIndent()

fun completeComposeSource(
    context: Context,
    config: GlassConfig,
    target: Target = Target.MINI,
): String {
    val parts =
        listOf("GlassConfig.kt", "GlassEngine.kt").map {
            context.assets.open("export/$it").bufferedReader().use { it.readText() }
        }
    val imports =
        (parts.flatMap { it.lines() }.filter { it.startsWith("import ") } +
                listOf(
                    "import androidx.compose.foundation.layout.*",
                    "import androidx.compose.ui.unit.*",
                ))
            .distinct()
    return buildString {
        appendLine("// Generated by DATZON Glass Lab. Android 13+; MIT notices in export ZIP.")
        appendLine("package id.datzon.glassexport")
        imports.forEach { appendLine(it) }
        parts.forEach { s ->
            appendLine(
                s.lines()
                    .filterNot { it.startsWith("package ") || it.startsWith("import ") }
                    .joinToString("\n")
            )
        }
        appendLine(COMPONENT_SOURCE)
        appendLine("val ExportedConfiguration = ${kotlinConfiguration(config)}")
        appendLine("val ExportedTarget = Target.${target.name}")
    }
}

fun copyText(context: Context, label: String, text: String) {
    (context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager).setPrimaryClip(
        ClipData.newPlainText(label, text)
    )
    Toast.makeText(context, "Copied $label", Toast.LENGTH_SHORT).show()
}

private fun zipExport(
    context: Context,
    uri: Uri,
    configs: Map<Target, GlassConfig>,
    target: Target,
) {
    val output =
        requireNotNull(context.contentResolver.openOutputStream(uri)) {
            "Cannot open export destination"
        }
    ZipOutputStream(output).use { zip ->
        fun add(name: String, text: String) {
            zip.putNextEntry(ZipEntry(name))
            zip.write(text.toByteArray())
            zip.closeEntry()
        }
        add("preset.json", LabPreset("DATZON export", configs).json())
        add("glass.agsl", GLASS_AGSL)
        add(
            "ExportedGlass.kt",
            completeComposeSource(context, configs[target] ?: originalConfig(target), target),
        )
        add(
            "DEPENDENCIES.md",
            """
            # Native Android integration
            Minimum SDK 33. Verified project versions: AGP 8.13.2, Gradle 8.13,
            Kotlin/Compose compiler plugin 2.2.21, Compose BOM 2025.10.01, JDK 17+, compile SDK 36.
            Dependencies: androidx.compose.ui:ui, ui-graphics, foundation, runtime.
            ExportedGlass.kt is ONE complete Kotlin file; no app-private utilities.
            Its shader and configuration catalog are the exact live preview implementation.
            Apply the Kotlin Compose compiler plugin to your module.

            Call ExportedGlassComponent(ExportedConfiguration, Modifier.fillMaxSize(), target=ExportedTarget,
                backdropContent = { /* live content */ }, glassContent = { /* controls */ }).
            For multiple moving objects, use rememberGlassBackdrop, recordBackdrop and
            GlassField directly. Source and GlassField must occupy the SAME local viewport.
            Keep the glass outside the content being recorded to prevent recursive capture.
            Geometry uses device pixels; optical distances are dp, converted by the engine.
            Never record a parent that also contains its GlassField readers.

            preset.json includes every target, including animation/gesture settings.
            ExportedGlassComponent exports the material primitive. DATZON dock state,
            gestures and artwork path are supplied separately as LabMotion.kt and NativePreview.kt.
            Those two source files use the id.datzon.glasslab package and the app's demo data.
            They are reference integration files, not part of the standalone material file.
            No production music services, credentials or private assets are included.
            """
                .trimIndent(),
        )
        listOf(
                "LabMotion.kt",
                "NativePreview.kt",
                "LabIcons.kt",
                "THIRD_PARTY_NOTICES.md",
                "SOURCE_PROVENANCE.md",
            )
            .forEach { file ->
                add(
                    file,
                    context.assets.open("export/$file").bufferedReader().use { it.readText() },
                )
            }
    }
}

@Composable
fun ExportPanel(
    target: Target,
    configs: Map<Target, GlassConfig>,
    onImport: (Map<Target, GlassConfig>) -> Unit,
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var status by remember { mutableStateOf("") }
    val latestConfigs by rememberUpdatedState(configs)
    val latestTarget by rememberUpdatedState(target)
    val export =
        rememberLauncherForActivityResult(
            ActivityResultContracts.CreateDocument("application/zip")
        ) { uri ->
            if (uri != null)
                scope.launch {
                    status = "Exporting…"
                    status =
                        runCatching {
                                withContext(Dispatchers.IO) {
                                    zipExport(context, uri, latestConfigs, latestTarget)
                                }
                                "Export saved"
                            }
                            .getOrElse { "Export failed: ${it.message}" }
                }
        }
    val exportJson =
        rememberLauncherForActivityResult(
            ActivityResultContracts.CreateDocument("application/json")
        ) { uri ->
            if (uri != null)
                scope.launch {
                    status =
                        runCatching {
                                withContext(Dispatchers.IO) {
                                    context.contentResolver
                                        .openOutputStream(uri)!!
                                        .bufferedWriter()
                                        .use {
                                            it.write(
                                                LabPreset("DATZON export", latestConfigs).json()
                                            )
                                        }
                                }
                                "Preset saved"
                            }
                            .getOrElse { "Save failed: ${it.message}" }
                }
        }
    val import =
        rememberLauncherForActivityResult(ActivityResultContracts.OpenDocument()) { uri ->
            if (uri != null)
                scope.launch {
                    status =
                        runCatching {
                                val preset =
                                    withContext(Dispatchers.IO) {
                                        context.contentResolver
                                            .openInputStream(uri)!!
                                            .bufferedReader()
                                            .use { reader ->
                                                val raw = reader.readText()
                                                require(raw.length < 1_000_000) {
                                                    "Preset is too large"
                                                }
                                                LabPreset.parse(raw)
                                            }
                                    }
                                onImport(preset.configs)
                                "Imported ${preset.configs.size} component settings"
                            }
                            .getOrElse { "Import failed: ${it.message}" }
                }
        }
    fun action(label: String, block: () -> Unit) {
        runCatching(block).onFailure { status = "$label failed: ${it.message}" }
    }
    SmallLabel("Export / native source")
    Note(
        "Target: ${target.label}. Complete source includes the current engine, supporting configuration types, AGSL and integration dependencies."
    )
    listOf(
            "Copy JSON Configuration" to
                {
                    copyText(
                        context,
                        "target.json",
                        (configs[target] ?: originalConfig(target)).json(target),
                    )
                },
            "Copy Kotlin Configuration" to
                {
                    copyText(
                        context,
                        "Configuration.kt",
                        kotlinConfiguration(configs[target] ?: originalConfig(target)),
                    )
                },
            "Copy Compose Component" to
                {
                    copyText(
                        context,
                        "ExportedGlass.kt",
                        completeComposeSource(
                            context,
                            configs[target] ?: originalConfig(target),
                            target,
                        ),
                    )
                },
            "Copy AGSL Shader" to { copyText(context, "glass.agsl", GLASS_AGSL) },
            "Export Complete Preset (.json)" to { exportJson.launch("DATZON-Glass-Preset.json") },
            "Export Source + Preset (.zip)" to { export.launch("DATZON-Glass-Native-Export.zip") },
            "Import JSON file" to
                {
                    import.launch(arrayOf("application/json", "text/*", "application/octet-stream"))
                },
            "Import JSON from clipboard" to
                {
                    val clipboard =
                        context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                    val raw =
                        clipboard.primaryClip?.getItemAt(0)?.coerceToText(context)?.toString()
                            ?: error("Clipboard is empty")
                    val parsed = LabPreset.parse(raw)
                    onImport(parsed.configs)
                    status = "Imported ${parsed.configs.size} components"
                },
        )
        .forEach { (label, block) ->
            OutlinedButton(onClick = { action(label, block) }, modifier = Modifier.fillMaxWidth()) {
                Text(label)
            }
        }
    if (status.isNotBlank()) Note(status)
}
